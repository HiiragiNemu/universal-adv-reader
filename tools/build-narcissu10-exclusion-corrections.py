"""Derive data-only selection corrections from the completed native content audit."""
import hashlib
import json
import pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
RESOURCE = pathlib.Path(r"D:\PROGETTO\narcissu-kana-research")
report = json.loads((ROOT / "reports/verification/content-repair-20261013/narcissu10/exclusion-decisions.json").read_text(encoding="utf-8"))
manifest = json.loads((RESOURCE / "manifests/generated/reader-adapter.json").read_text(encoding="utf-8"))
stories = {s["canonicalStoryId"]:s for s in manifest["stories"]}
def variant(story):
    return next((v for v in story["variants"] if v["sourceLocale"] == "ja-JP" and "original-ja-jp" in v["id"]),
                next(v for v in story["variants"] if v["sourceLocale"] == "ja-JP"))
def source_hashes(identities):
    paths = [variant(stories[identity])["references"]["source"] for identity in identities]
    return {p:hashlib.sha256((RESOURCE / p).read_bytes()).hexdigest() for p in paths}
def correction(identity, reason, evidence, source_identities=None):
    s = stories[identity]
    return {"canonicalStoryId":identity,"fromDecision":s["resource"]["reader"]["decision"],
        "fromReason":s["resource"]["reader"]["reasonCode"],"expectedEntryReachable":s["resource"]["entryReachable"],
        "decision":"exclude","resourceClass":"archive","reasonCode":reason,
        "evidence":evidence + ["reports/verification/content-repair-20261013/narcissu10/exclusion-decisions.json"],
        "sources":source_hashes(source_identities or [identity])}
corrections = []
for review in report["draftContentReviews"]:
    if review["oldReason"] != "engine-sample" or review["reviewedTextClass"] != "unreferenced-bundled-fiction-draft":
        continue
    corrections.append(correction(review["storyId"],"bundled-narrative-draft-without-confirmed-menu-entry",[
        str(review["rawTextEvents"]) + " native text events contain fictional narrative prose, not engine/UI sample instructions.",
        "This archived narrative family contains the rain-world prose and characters 郎女/巫女; no attribution to a released Narcissu route is inferred from the filename.",
        "Every N10 native variant was scanned for exact script-name literals; no incoming exact-name reference was found for this member. Dynamic name construction was not proved impossible, and a current menu entry is unconfirmed.",
        "Preserve the original member as an archived narrative draft; the old engine-sample reason was too broad.",
    ]))
himeko = report["himekoComposite"]
corrections.append(correction(himeko["whole"]["canonicalStoryId"],"split-chapter-body-with-author-assembly-notes",[
    "The original temporary assembly has 1,500 text events: 1,492 body units are already present in himeko_ep00/01/02.",
    "The eight unmatched events (indices 0,1,26,27,28,29,30,31) are author/integration notes, including the explicit temporary-assembly heading and a statement that the body is unchanged.",
    "The binary and complete text stream are not identical to the split chapters. The reader uses the split native chapters and preserves these assembly notes in the archive.",
], [himeko["whole"]["canonicalStoryId"]] + [s["canonicalStoryId"] for s in himeko["parts"]]))
iris = report["irisComposite"]
corrections.append(correction(iris["whole"]["canonicalStoryId"],"combined-chapter-body-with-minor-display-revision",[
    "The native start references the combined novel; the reader instead presents all nine ordered nar3_00 through nar3_08 chapters.",
    "Complete normalized body comparison found only three edits: an ellipsis, a repeated ヨハン quote/speaker boundary, and an added っ. No additional scene is present.",
    "The 4,350 combined text events and 4,347 split text events use different pause/line segmentation; they are not byte-identical. Original source and all three exact character differences are retained in the audit.",
], [iris["whole"]["canonicalStoryId"]] + [s["canonicalStoryId"] for s in iris["parts"]]))
assert len({c["canonicalStoryId"] for c in corrections}) == len(corrections)
output = ROOT / "tools/lib/narcissu10-exclusion-corrections.mjs"
output.write_text("// Byte-bound exclusion evidence. Generated by tools/build-narcissu10-exclusion-corrections.py.\n"
    + "export const NARCISSU10_EXCLUSION_CORRECTIONS = "
    + json.dumps(corrections,ensure_ascii=False,indent=2) + ";\n",encoding="utf-8")
print(json.dumps({"output":str(output),"corrections":len(corrections),
    "engineSampleLabelsCorrected":sum(c["fromReason"]=="engine-sample" for c in corrections),
    "includesAdded":0},ensure_ascii=False))
